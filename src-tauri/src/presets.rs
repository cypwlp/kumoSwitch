#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::BTreeSet;

    #[test]
    fn presets_are_complete_and_unique() {
        assert!(PRESETS.len() >= 28);
        let mut ids = BTreeSet::new();
        for preset in PRESETS {
            assert!(ids.insert(preset.id), "duplicate id: {}", preset.id);
            assert!(!preset.name.is_empty(), "{}", preset.id);
            assert!(preset.website_url.starts_with("https://"), "{}", preset.id);
            assert!(preset.docs.starts_with("https://"), "{}", preset.id);
            assert!(["api_key", "oauth", "local"].contains(&preset.auth_type), "{}", preset.id);
            assert!(
                ["account", "official", "third_party", "cloud", "local", "unified"].contains(&preset.category),
                "{}",
                preset.id
            );
            if preset.auth_type == "api_key" || preset.auth_type == "local" {
                assert!(preset.base_url.starts_with("http://") || preset.base_url.starts_with("https://"), "{}", preset.id);
                assert!(!preset.models.is_empty(), "{}", preset.id);
            } else {
                assert_eq!(preset.category, "account", "{}", preset.id);
                assert!(preset.base_url.is_empty(), "{}", preset.id);
                assert!(!preset.login_hint.is_empty(), "{}", preset.id);
            }
        }
    }

    #[test]
    fn required_catalog_entries_exist() {
        for id in [
            "openai", "anthropic", "gemini", "xai", "deepseek", "moonshot", "zhipu",
            "dashscope", "minimax", "openrouter", "groq", "siliconflow", "ollama",
            "lmstudio", "opencode-zen", "commandcode",
        ] {
            assert!(PRESETS.iter().any(|preset| preset.id == id), "missing {id}");
        }
    }
}
